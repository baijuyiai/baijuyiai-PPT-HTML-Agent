-- 图表视觉风格：一个项目级旋钮，决定图表怎么画（配色、圆角、渐变、标记、网格……）。
--
-- **跟着项目走，不跟着风格文档走。** 页面风格（StyleDoc）给的是底色、文字色、字体，
-- 图表风格给的是「图怎么画」——两者是不同的维度：同一套页面风格下，
-- 一本技术白皮书想要「经典」（图表跟着页面配色、克制），
-- 一本数据汇报想要「数据看板」（五色板、圆角、渐变）。
--
-- 取值见 `@lumen/charts` 的 `CHART_STYLE_IDS`（dashboard / classic）。
-- **给默认值而不是可空**：读取侧不该处理第三种状态，而新项目本来就该拿到新的那套。
-- 老项目没有这一列，加列时按默认值补上——它们的图表页是这次改动之前生成的、
-- 页面里根本没有图表槽，所以看不出任何变化。
ALTER TABLE projects ADD COLUMN chartStyle TEXT NOT NULL DEFAULT 'dashboard';
